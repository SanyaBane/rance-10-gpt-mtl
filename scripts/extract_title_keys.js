/**
 * Find the character names Ｔ肩書き compares its argument against.
 *
 *   npm run regenerate-title-keys
 *
 * A speaker's title is not a field of anything: Ｔ肩書き is 313 compares of one
 * string argument, each answered by returning the slot that holds that
 * character's title, and AdvNamePlate@InnerCreate is its only caller. The
 * shape in the code dump is
 *
 *     PUSHLOCALPAGE / PUSH 0x0 / REF / A_REF        <- .LOCALREF ▲名前
 *     S_PUSH <slot> / S_EQUALE
 *
 * and which slots those are is nowhere but in that code -- the dump of the
 * strings cannot tell a key from a title, and the cherry-picks translate both.
 * So this reads them out into game/extracted/title_keys.v1.04.tsv, and
 * modules/TitleKeys.js renders the .jaf that maps a translated key back to the
 * Japanese the compare wants. docs/title-keys.md has the whole of it.
 *
 * Every compare is against the argument -- there are no compares of anything
 * else in the function -- so the four-instruction preamble is checked rather
 * than assumed: a version that starts testing a global here would otherwise
 * quietly file the global's string as a character.
 */
import * as fs from "fs/promises";
import * as os from "os";
import * as path from "path";
import {AIN, AIN_TXT} from "../modules/AinFiles.js";
import {alice, run} from "../modules/AliceTools.js";
import {ROOT} from "../modules/Env.js";
import {readAinStrings} from "../modules/EnemyInfo.js";
import {scanTitleKeys, TITLE_FUNCTION, TITLE_KEYS} from "../modules/TitleKeys.js";

run(async () => {
    const tempDir = await fs.mkdtemp(path.join(os.tmpdir(), "rance10-title-keys-"));
    const codeDump = path.join(tempDir, "code.jam");
    try {
        const status = alice(["ain", "dump", "-C", "--no-macros", "-o", codeDump, AIN]);
        if (status !== 0) {
            return status;
        }
        const slots = await scanTitleKeys(codeDump, TITLE_FUNCTION);
        const strings = await readAinStrings(AIN_TXT);

        const header = [
            `# The character names ${TITLE_FUNCTION} looks a nameplate title up by.`,
            "# Generated by scripts/extract_title_keys.js -- nobody edits this file, and",
            "# the English comes from patches/system_cherry_picks.v1.04.ain.txt.",
            "#",
            "# Columns: the string slot <TAB> the Japanese, JSON-quoted.",
            "# The Japanese is here to be read: modules/TitleKeys.js pairs the slot with the",
            "# dump itself, so the .jaf cannot disagree with the game about what a key says.",
            "",
        ].join("\n");
        const rows = slots.map((slot) => `${slot}\t${JSON.stringify(strings.get(slot) ?? "")}`);
        await fs.writeFile(TITLE_KEYS, header + rows.join("\n") + "\n", "utf-8");

        console.log(`Found ${rows.length} nameplate title keys in ${TITLE_FUNCTION}`
            + ` -> ${path.relative(ROOT, TITLE_KEYS)}`);
        return 0;
    } finally {
        await fs.rm(tempDir, {recursive: true, force: true});
    }
});
